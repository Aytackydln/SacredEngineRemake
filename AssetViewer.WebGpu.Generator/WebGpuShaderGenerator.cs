using System;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace AssetViewer.WebGpu.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class WebGpuShaderGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor CompilationFailed = new("WGSL001", "WebGPU shader generation failed",
        "{0}: {1}", "Shaders", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inputs = context.AdditionalTextsProvider.Where(file => file.Path.EndsWith(".hlsl", StringComparison.OrdinalIgnoreCase))
            .Select((file, cancellation) => (Name: Path.GetFileName(file.Path),
                Content: file.GetText(cancellation)?.ToString().Replace("\r\n", "\n") ?? ""));
        var programs = inputs.Collect().SelectMany((files, _) => ShaderProgram.Create(files))
            .WithTrackingName("ShaderPrograms");
        var compilerRoot = context.AnalyzerConfigOptionsProvider.Select((options, _) =>
            options.GlobalOptions.TryGetValue("build_property.WebGpuSlangRoot", out var root) ? root : "");
        context.RegisterSourceOutput(programs.Combine(compilerRoot), (output, input) =>
        {
            var program = input.Left;
            var source = new StringBuilder("// <auto-generated/>\nnamespace AssetViewer.Browser.Rendering;\ninternal static partial class WebGpuShaderSources\n{\n");
            source.Append("    private static void Register").Append(program.Name).Append("()\n    {\n");
            try
            {
                if (program.Error is { } error) throw new InvalidOperationException(error);
                if (string.IsNullOrWhiteSpace(input.Right))
                    throw new InvalidOperationException("The WebGpuSlangRoot compiler property is missing.");
                using var compiler = new SlangCompiler(input.Right, output.CancellationToken);
                foreach (var stage in program.Stages)
                {
                    var wgsl = compiler.Compile(program, stage, output.CancellationToken);
                    source.Append("        WebGpuInterop.RegisterShader(\"").Append(program.Name).Append('.').Append(stage)
                        .Append("\", ").Append(SymbolDisplay.FormatLiteral(wgsl, quote: true)).Append(");\n");
                }
            }
            catch (OperationCanceledException) { throw; }
            catch (Exception error)
            {
                output.ReportDiagnostic(Diagnostic.Create(CompilationFailed, Location.None, program.Name, error.Message));
            }
            source.Append("    }\n}\n");
            output.AddSource(program.Name + ".wgsl.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
        context.RegisterPostInitializationOutput(output => output.AddSource("WebGpuShaderSources.g.cs", SourceText.From(
            "// <auto-generated/>\nnamespace AssetViewer.Browser.Rendering;\ninternal static partial class WebGpuShaderSources\n{\n" +
            "    internal static void Register()\n    {\n" +
            string.Join("\n", ShaderProgram.Names.Select(name => "        Register" + name + "();")) + "\n    }\n}\n", Encoding.UTF8)));
    }
}
