using System.Text.Json;
using Sacred.Core.Runtime;
using Sacred.GameplayHost.Equipment;
using Sacred.GameplayHost.Scripting;
using Sacred.Network.Gameplay;

internal static class HostWeaponGenerationChecks
{
    public static int Run(string root)
    {
        using var proof = JsonDocument.Parse(File.ReadAllText(Path.Combine(root,
            "docs/game-server/evidence/native-host-weapon-generation.json")));
        var data = EquipmentGenerationFixture.ReadStartup(root);
        var checks = 0;
        foreach (var row in proof.RootElement.GetProperty("cases").EnumerateArray())
        {
            var original = Bytes(row, "initial_hex");
            var random = new SacredRandomSequence(row.GetProperty("seed").GetUInt32());
            var generator = new WorldEquipmentOrdinaryGeneration(data)
                { Naming = new WorldEquipmentNames(data), Precision = SacredX87Precision.Single };
            var values = generator.Generate(System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(original),
                row.GetProperty("level").GetUInt16(), row.GetProperty("difficulty").GetUInt32(), original,
                random, row.GetProperty("quality").GetUInt32());
            Check(values.AsSpan().SequenceEqual(Bytes(row, "values_hex")), "all 130 generated bytes and final price");
            Check(generator.GeneratedName?.NativeReference == row.GetProperty("name_reference").GetUInt32(), "actual object-context generated name");
            Check(random.State == row.GetProperty("rng_after").GetUInt32(), "complete native generation/name RNG consumption");
            Check(original.AsSpan().SequenceEqual(Bytes(row, "initial_hex")), "authored source remains immutable");
            var references = new GoldObjectReferencePool(); references.Apply(GoldReferenceBatch.FromPayload(BitConverter.GetBytes(17u)));
            var activation = new WorldObjectActivationQueue();
            var factory = new WorldEquipmentInitialFactory(references, new WorldObjectAllocationCounter(), activation, 1);
            var resource = System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(original);
            var item = factory.Create(data.Templates.GetItem(resource), original, 0, networking: true);
            random = new SacredRandomSequence(row.GetProperty("caller_seed").GetUInt32());
            WorldScriptInitialWeaponValues.Apply(item, 9, row.GetProperty("level").GetUInt16(), row.GetProperty("difficulty").GetUInt32(), data, random);
            Check(item.Values.AsSpan().SequenceEqual(values) && item.Physical.Base.Word3C == row.GetProperty("name_reference").GetUInt32(), "integrated actual item values and name identity");
            Check(item.Quality == row.GetProperty("quality").GetUInt32() && item.LegacyGenerationSelector == row.GetProperty("legacy").GetUInt32() &&
                random.State == row.GetProperty("rng_after").GetUInt32(), "quality first, legacy second, then actual generation/name draws");
        }
        return checks;
        void Check(bool condition, string reason) { if (!condition) throw new Exception("Host weapon generation: " + reason); checks++; }
    }
    private static byte[] Bytes(JsonElement row, string key) => Convert.FromHexString(row.GetProperty(key).GetString()!);
}
