namespace Sacred.Network.Gameplay;

/// <summary>Gold 0x79CAD0 copies native +0x20A0..+0x252B as one 0x48C-byte
/// derived block. The stream has a size prefix without the opening derived marker.
/// Native-offset names retain fields whose individual semantics are unresolved.</summary>
public static class GoldMagicPrisonParticleLayout
{
    public const int DerivedSize = 0x48C;
    /// <summary>Float incremented by the supplied delta in native 0x79C9F0.</summary>
    public const int ElapsedOffset = 0;
    public const int Native20A4ByteOffset = 4;
    /// <summary>Transmitted constructor backing, not initialized by Start.
    /// The compared update/full-render paths at detail 0..2 do not read these bytes.</summary>
    public const int Native20A5BytesOffset = 5;
    public const int Native20A5BytesSize = 3;
    /// <summary>256 packed color words generated by Start at native +0x20A8.</summary>
    public const int ColorTableOffset = 8;
    public const int ColorCount = 256;
    public const int Native24A8BlockOffset = 0x408;
    public const int Native24A8BlockSize = 0x20;
    public const int Native24C8BlockOffset = 0x428;
    public const int Native24C8BlockSize = 0x64;
    /// <summary>Float selected from DETAILLEVEL byte 0x182EE78 by Start.
    /// Configuration defaults to two; the field's wider lifecycle remains separate.</summary>
    public const int Native2520FloatOffset = 0x480;
}
