namespace Sacred.GameServer.Session;

/// <summary>How the original GameServer.exe treats an opcode and how this server handles it.</summary>
public enum OpcodeClass : byte
{
    /// <summary>Pure forward (FUN_004D3EA0 with a recipient mode).</summary>
    Forward,
    /// <summary>Updates the original's own world state, then forwards; the state part is a TODO here.</summary>
    ForwardAfterState,
    /// <summary>Applied to the original's own state only; nothing is sent.</summary>
    Consumed,
    /// <summary>Answered by the server (explicit handler).</summary>
    Answered,
    /// <summary>Commands of the original's own lobby/menu threads: accepted from clients there, dropped here on purpose.</summary>
    Internal,
    /// <summary>Handled before the routing (admission).</summary>
    Admission,
    /// <summary>Case that does nothing.</summary>
    NoOp,
    /// <summary>Has a network effect in the original that needs state this server does not model; dropped silently for now.</summary>
    Todo,
}

/// <summary>One case of the original dispatcher <c>FUN_004C3F20</c>.</summary>
public readonly record struct OpcodeEntry(ushort Opcode, int Address, OpcodeClass Class, string Handling);

