using System.Text;
using Iced.Intel;
using Sacred.Particles.Reader.Evaluation;
using Sacred.Particles.Reader.Executable;

namespace Sacred.Particles.Reader.Generation;

internal static class FxAttachmentSourceWriter
{
    public static string Write(string executable)
    {
        var image = SacredExecutableImage.Load(executable);
        var code = new NativeCode(image);
        var source = new StringBuilder("// <auto-generated />\n// Native cObjectFX wearer branches and bone names; regenerate with Sacred.Particles.Reader.\nnamespace Sacred.Particles.Generated;\ninternal static class EmbeddedFxAttachments\n{\n    internal static readonly IReadOnlyList<SacredFxAttachmentDefinition> Definitions = Array.AsReadOnly<SacredFxAttachmentDefinition>([\n");
        var count = (uint)code.At(0x5A3AF6).GetImmediate(1) + 1;
        for (uint subtype = 1; subtype <= count; subtype++)
        {
            var start = image.UInt32(0x5A5EC4 + (subtype - 1) * 4);
            // This native branch resolves the wearer, then calls 44CB80 (neck 3, or root 0).
            if (start == 0x5A5354)
            {
                source.AppendLine($"        new({subtype}u, 3, false, 0x{start:X}u) {{ FallbackBone = 0 }},");
                continue;
            }
            try
            {
                var a = Evaluate(start, subtype, 0);
                var b = Evaluate(start, subtype, 1);
                if (a.Wearer != 0x1111 || b.Wearer != 0x1111 || a.Extras || b.Extras) continue;
                var dynamic = a.Bone == 0 && b.Bone == 1;
                if (!dynamic && a.Bone != b.Bone) continue;
                source.AppendLine($"        new({subtype}u, {a.Bone}, {(dynamic ? "true" : "false")}, 0x{start:X}u),");
            }
            catch (Exception error) when (error is NotSupportedException or InvalidDataException or OverflowException)
            {
                // Complex owner commands, multi-bone geometry and runtime lookups remain explicit gaps.
            }
        }
        source.AppendLine("    ]);\n    internal static readonly IReadOnlyList<string> BoneNames = Array.AsReadOnly<string>([");
        // Version-checked native table ends where the following texture strings begin.
        for (uint address = 0x8E7200; address < 0x8E7AC0; address += 32)
            source.AppendLine($"        {CSharpLiteral.String(image.String(address, 32))},");
        source.AppendLine("    ]);\n}");
        return source.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);

        (uint Wearer, ushort Bone, bool Extras) Evaluate(uint start, uint subtype, uint selector)
        {
            var memory = new PresetMemory(image, 0x200, SacredParticleQuality.High);
            var state = memory.BaseAddress;
            var argument = state + 0x2000;
            var stack = state + 0x7000;
            var done = state + 0x1FF00;
            memory.Write(state + 0x44, 4, subtype);
            memory.Write(argument + 4, 4, subtype);
            memory.Write(argument + 8, 4, 0x1111);
            memory.Write(argument + 12, 4, 0x2222);
            memory.Write(argument + 0x38, 4, 3);
            memory.Write(argument + 0x3C, 4, selector);
            memory.Write(state + 0x6E, 2, 1);
            var machine = new X86Machine(code, memory)
            {
                Boundary = cpu =>
                {
                    if (cpu.InstructionPointer is 0x5A3BF8 or 0x5A3BFE or 0x5A3C05)
                    { cpu.InstructionPointer = done; return true; }
                    return false;
                }
            };
            machine.Registers.Set(Register.EBP, state);
            machine.Registers.Set(Register.EBX, argument);
            machine.Registers.Set(Register.ESI, state + 0x4000);
            machine.Registers.Set(Register.EAX, 15);
            machine.Registers.Set(Register.ECX, subtype - 1);
            machine.Registers.Set(Register.ESP, stack);
            machine.Run(start, done, CancellationToken.None);
            return ((uint)memory.Integer(state + 0x68, 4), (ushort)memory.Integer(state + 0x70, 2),
                memory.Integer(state + 0x72, 2) != 0 || memory.Integer(state + 0x74, 4) != 0);
        }
    }
}
