using System.Globalization;
using Sacred.Particles.Reader.Decoding;
using Sacred.Particles.Reader.Executable;

namespace Sacred.Particles.Reader.Generation;

internal static class DeflectionFxSourceWriter
{
    public static string Write(string executable)
    {
        var image = SacredExecutableImage.Load(executable);
        var code = new NativeCode(image);
        string Operand(uint address) => image.Single((uint)code.At(address).MemoryDisplacement64)
            .ToString("R", CultureInfo.InvariantCulture) + "f";
        var capacity = NativeParticleCapacityReader.Read(code, 0x5A0D6B);
        var points = (int)code.At(0x76C6DE).GetImmediate(1);
        var colors = new uint[] { 0x76C16F, 0x76C16F, 0x76C21D, 0x76C260, 0x76C2B0 }
            .Select(address => $"0x{code.At(address).GetImmediate(1):X8}u");
        return "// <auto-generated />\n// Gold deflection line-strip constructor/update operands.\nnamespace Sacred.Particles.Generated;\n" +
            "internal static class EmbeddedDeflectionFx\n{\n    internal static readonly SacredDeflectionFxDefinition Definition = " +
            $"new({capacity / points}, {points}, {Operand(0x76C4A7)}, {Operand(0x76C4DC)}, {Operand(0x76C5A6)}, " +
            $"{BitConverter.UInt32BitsToSingle(code.At(0x76C3B6).Immediate32).ToString("R", CultureInfo.InvariantCulture)}f, " +
            $"{Operand(0x76C5E0)}, {Operand(0x76C32D)}, {Operand(0x76C396)}, {Operand(0x76C3CE)}, {Operand(0x76C3D4)}, {Operand(0x76C327)}, " +
            $"Array.AsReadOnly<uint>([{string.Join(", ", colors)}])) {{ AttachmentSubtype = {code.At(0x532A67).GetImmediate(0)}u }};\n}}\n";
    }
}
