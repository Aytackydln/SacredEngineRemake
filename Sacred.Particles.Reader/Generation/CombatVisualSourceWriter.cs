using System.Globalization;
using System.Text;
using Sacred.Particles.Reader.Decoding;
using Sacred.Particles.Reader.Executable;

namespace Sacred.Particles.Reader.Generation;

internal static class CombatVisualSourceWriter
{
    public static string Write(string executable)
    {
        var image = SacredExecutableImage.Load(executable);
        var source = new StringBuilder("// <auto-generated />\n// CA factory outputs decoded from Sacred.exe; regenerate with Sacred.Particles.Reader.\n// Native code SHA256: " + image.CodeSha256 + "\nnamespace Sacred.Particles.Generated;\ninternal static class EmbeddedCombatVisuals\n{\n    internal static readonly IReadOnlyList<SacredCombatVisualDefinition> Definitions = Array.AsReadOnly<SacredCombatVisualDefinition>([\n");
        foreach (var d in NativeCombatVisualReader.Read(image))
            source.AppendLine($"        new(Sacred.Core.CombatArts.SacredCombatArtKind.{d.Kind}, {d.Code}u, {d.Resource}u, {d.FxSubtype}u, {CSharpLiteral.String(d.Bone)}, {(d.TargetIsCaster ? "true" : "false")}, {Float(d.ReleaseProgress)}, {d.DurationBase}, {d.DurationPerLevel}, {d.DurationCap}, 0x{d.NativeAddress:X}u) {{ Direction = new({Float(d.Direction.X)}, {Float(d.Direction.Y)}, {Float(d.Direction.Z)}), Diagnostic = {CSharpLiteral.String(d.Diagnostic)} }},");
        source.AppendLine("    ]);\n}");
        return source.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }
    private static string Float(float value) => value.ToString("R", CultureInfo.InvariantCulture) + "f";
}
