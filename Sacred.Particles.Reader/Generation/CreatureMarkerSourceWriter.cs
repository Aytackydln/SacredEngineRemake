using System.Globalization;
using Sacred.Particles.Reader.Executable;

namespace Sacred.Particles.Reader.Generation;

internal static class CreatureMarkerSourceWriter
{
    public static string Write(string executable)
    {
        var image = SacredExecutableImage.Load(executable);
        var code = new NativeCode(image);
        // cGranny calls the texture manager directly (one call), unlike particle constructors' two-call lookup.
        string Texture(uint push) => CSharpLiteral.String(image.String((uint)code.At(push).GetImmediate(0), 128));
        string Operand(uint address) => image.Single((uint)code.At(address).MemoryDisplacement64)
            .ToString("R", CultureInfo.InvariantCulture) + "f";
        return "// <auto-generated />\n// cGranny ground-symbol draws decoded from Sacred.exe.\nnamespace Sacred.Particles.Generated;\n" +
            "internal static class EmbeddedCreatureMarkers\n{\n    internal static readonly SacredCreatureMarkerDefinition Definition = " +
            $"new({Texture(0x40128D)}, {Texture(0x40129F)}, {Texture(0x4012B1)}, {Texture(0x4012C3)}, -({Operand(0x408802)}), {Operand(0x408AB0)});\n}}\n";
    }
}
